constexpr size_t RETRO_BGM_SIZE = sizeof(RETRO_BGM_DATA);

static bool s_initialized = false;
static bool s_bgmPlaying = false;
static bool s_sfxEnabled = true;

#ifdef _WIN32
static HMIDIOUT s_hMidi = nullptr;
#endif

void init() {
    if (s_initialized) return;

#ifdef _WIN32
    // Ensure retro_bgm.mid file is present on disk for MCI sequencer
    const char* bgmPath = "retro_bgm.mid";
    std::ifstream check(bgmPath, std::ios::binary);
    if (!check.good()) {
        std::ofstream out(bgmPath, std::ios::binary);
        if (out.is_open()) {
            out.write(reinterpret_cast<const char*>(RETRO_BGM_DATA), RETRO_BGM_SIZE);
            out.close();
        }
    }

    mciSendStringA("open \"retro_bgm.mid\" type sequencer alias bgm", NULL, 0, NULL);

    // Open MIDI synthesizer device for zero-latency 8-bit sound effects
    if (midiOutOpen(&s_hMidi, MIDI_MAPPER, 0, 0, CALLBACK_NULL) == MMSYSERR_NOERROR) {
        // Set channel 2 instrument: Program 80 (Square Lead)
        midiOutShortMsg(s_hMidi, 0x0050C2);
    }
#endif

    s_initialized = true;
}

void shutdown() {
    if (!s_initialized) return;

#ifdef _WIN32
    stopBGM();
    mciSendStringA("close bgm", NULL, 0, NULL);

    if (s_hMidi) {
        midiOutReset(s_hMidi);
        midiOutClose(s_hMidi);
        s_hMidi = nullptr;
    }
#endif

    s_initialized = false;
}

void startBGM() {
    if (!s_initialized) init();

#ifdef _WIN32
    mciSendStringA("seek bgm to start", NULL, 0, NULL);
    mciSendStringA("play bgm repeat", NULL, 0, NULL);
#endif
    s_bgmPlaying = true;
}

void stopBGM() {
#ifdef _WIN32
    mciSendStringA("stop bgm", NULL, 0, NULL);
#endif
    s_bgmPlaying = false;
}

void toggleBGM() {
    if (s_bgmPlaying) {
        stopBGM();
    } else {
        startBGM();
    }
}

bool isBGMPlaying() {
    return s_bgmPlaying;
}

void toggleSFX() {
    s_sfxEnabled = !s_sfxEnabled;
}

bool isSFXEnabled() {
    return s_sfxEnabled;
}

void playSFX(SFX sound) {
    if (!s_sfxEnabled) return;

#ifdef _WIN32
    if (s_hMidi) {
        switch (sound) {
            case SFX::Move:
                // Rapid arcade blip: Note G4 (67), velocity 100 on ch2
                midiOutShortMsg(s_hMidi, 0x00644392);
                break;

            case SFX::Merge:
                // Bright power-up chime: Note C5 (72) then E5 (76)
                midiOutShortMsg(s_hMidi, 0x007F4892);
                break;

            case SFX::Win:
                // Victory chord: C5 + G5
                midiOutShortMsg(s_hMidi, 0x007F4892);
                midiOutShortMsg(s_hMidi, 0x007F4F92);
                break;

            case SFX::GameOver:
                // Low descent note: C3 (48)
                midiOutShortMsg(s_hMidi, 0x007F3092);
                break;
        }
    }
#endif
}

